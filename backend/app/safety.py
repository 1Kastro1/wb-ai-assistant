import re

VIN = re.compile(r'\b[A-HJ-NPR-Z0-9]{17}\b', re.I)
HIGH = ('хуже тормоз', 'плохо тормоз', 'ухудшен', 'провалива', 'дым', 'перегрев', 'заклини', 'утеч', 'скрежет', 'сильн', 'не тормоз', 'отказ тормоз')
CRITICAL = ('тормоз', 'колод', 'суппорт', 'рулев', 'шаров', 'ступиц', 'подвеск', 'диск')
FORBIDDEN = ('это нормально', 'притрутся', 'неправильно установили', 'плохие диски', 'точно брак', 'точно не брак', 'продолжайте ездить', 'гарантируем', 'компенсац', 'напишите продавцу', 'свяжитесь с продавцом', 'обратитесь к продавцу')


def review_intent(text):
    value = ' '.join(text.lower().replace('ё', 'е').split())
    if any(x in value for x in ('не тот товар', 'другой товар', 'пришел не тот', 'прислали не тот', 'получил не тот')):
        return 'WRONG_ITEM'
    if any(x in value for x in ('нет детал', 'не хватает', 'неполная комплектац', 'не доложили')):
        return 'MISSING_PARTS'
    if any(x in value for x in ('сломан', 'разбит', 'поврежден', 'помят')):
        return 'DAMAGED_ITEM'
    if any(x in value for x in ('не подошел', 'не подходит', 'несовместим')):
        return 'FITMENT_PROBLEM'
    if any(x in value for x in ('не увидел результата', 'не увидела результата', 'нет результата', 'не помог', 'не помогло', 'не очищает', 'не очистил', 'не отмыл', 'не отмыла')):
        return 'NO_RESULT'
    return 'GENERAL'


def mask_vin(text):
    return VIN.sub(lambda m: m[0][:3] + '***********' + m[0][-3:], text)


def classify(text, category=''):
    value = (text + ' ' + category).lower()
    critical = any(x in value for x in CRITICAL)
    high = critical and any(x in text.lower() for x in HIGH)
    caution = critical and any(x in text.lower() for x in ('скрип', 'свист', 'шум'))
    return {'risk': 'HIGH' if high else 'CAUTION' if caution else 'NORMAL', 'manual': high, 'safety_critical': critical,
            'topics': [x for x in ('упаков', 'достав', 'запах', 'скрип', 'вибрац', 'тормоз', 'подбор', 'совместим') if x in value] or ['другое']}


def validate_reply(text):
    if not 2 <= len(text.strip()) <= 5000:
        raise ValueError('Ответ должен содержать от 2 до 5000 символов')
    if VIN.search(text):
        raise ValueError('Полный VIN запрещён в публичном ответе')
    if any(x in text.lower() for x in FORBIDDEN):
        raise ValueError('Ответ содержит запрещённое обещание или небезопасное утверждение')
    if re.search(r'совместимость\s+подтверждена|(?:точно|полностью|гарантированно)\s+под(?:ходит|ойдут)|подходит\s+(?:к|для|на)\s+ваш', text, re.I):
        raise ValueError('Подтверждать применяемость можно только по проверенному результату каталога')
    return text.strip()


def rule_reply(review, product):
    if not review.text.strip():
        if review.rating >= 4:
            return 'Здравствуйте! Спасибо за вашу оценку. Рады, что вы выбрали наш товар!'
        return 'Здравствуйте! Спасибо за оценку. Нам важно понять, что можно улучшить. Если будет возможность, напишите, пожалуйста, что именно вас не устроило.'
    if review_intent(review.text) == 'WRONG_ITEM':
        return 'Здравствуйте! Приносим искренние извинения за то, что вам пришёл не тот товар. Вы можете оформить возврат через приложение или личный кабинет Wildberries и следовать подсказкам площадки. Если при оформлении потребуется, приложите фотографии полученного товара и упаковки. Спасибо, что сообщили нам об этой ситуации.'
    if review.risk == 'HIGH':
        return 'Здравствуйте! Нам жаль, что возникла такая ситуация. Описанные симптомы требуют проверки тормозной системы специалистом до дальнейшей эксплуатации. По отзыву установить причину невозможно. Пожалуйста, обратитесь в сервис для диагностики.'
    if review.risk == 'CAUTION':
        return 'Здравствуйте! Спасибо за обратную связь. У скрипа тормозных колодок могут быть разные причины. По одному отзыву установить причину невозможно. Рекомендуем проверить тормозную систему и установку в сервисе. Напишите нам о результатах проверки — поможем разобраться.'
    if product.brand.upper() == 'EIKOSHA' and any(x in review.text.lower() for x in ('пах', 'аромат', 'запах')):
        return 'Здравствуйте! Жаль, что аромат показался слабым. Восприятие запаха индивидуально; EIKOSHA отличается мягким, ненавязчивым ароматом. Попробуйте разместить ароматизатор ближе к потоку воздуха, соблюдая инструкцию вашей модели.'
    product_text = (product.name + ' ' + product.category).lower()
    if any(x in review.text.lower() for x in ('пах', 'аромат', 'запах', 'воня')) and any(x in product_text for x in ('аромат', 'парфюм', 'запах')):
        return 'Здравствуйте! Нам жаль, что аромат вам не понравился. Восприятие запахов индивидуально. Спасибо, что поделились впечатлением.'
    if review.rating >= 4 and any(x in review.text.lower() for x in ('смол', 'гудрон')) and 'очист' in product_text:
        return safe_fallback_reply(review, product)
    return None


